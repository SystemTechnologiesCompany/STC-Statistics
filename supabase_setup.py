"""Prepare private Supabase signing material and verify deployment before release."""
import argparse
import base64
import getpass
import hashlib
import json
from pathlib import Path
import sys
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from licensing_server.manage import provision_public
from stc_statistics.licensing import LicenseClient,CredentialStore,LicenseError

ROOT=Path(__file__).resolve().parent
PROJECT='zwjhjfgoiofbiyguhcbx'
URL=f'https://{PROJECT}.supabase.co/functions/v1/stc-license'
PRIVATE=ROOT/'.licensing_private/supabase'


def dashboard_source(root=ROOT):
    source=root/'supabase/functions/stc-license'
    parts=[]
    for name in ('protocol.ts','handler.ts','index.ts'):
        parts.append('\n'.join(line for line in (source/name).read_text(encoding='utf-8').splitlines()
                               if not line.startswith('import ')))
    return '// Generated by supabase_setup.py. Deploy as stc-license. No private keys in this file.\n'+'\n\n'.join(parts)+'\n'


def prepare():
    PRIVATE.mkdir(parents=True,exist_ok=True)
    path=PRIVATE/'signing-key.pem'
    if path.exists():
        key=serialization.load_pem_private_key(path.read_bytes(),password=None)
    else:
        key=rsa.generate_private_key(public_exponent=65537,key_size=3072)
        path.write_bytes(key.private_bytes(serialization.Encoding.PEM,serialization.PrivateFormat.PKCS8,serialization.NoEncryption()))
        path.chmod(0o600)
    if not isinstance(key,rsa.RSAPrivateKey) or key.key_size!=3072:
        raise ValueError('Expected a 3072-bit RSA private key')
    numbers=key.public_key().public_numbers()
    spki=key.public_key().public_bytes(serialization.Encoding.DER,serialization.PublicFormat.SubjectPublicKeyInfo)
    public={'server_url':URL,'public_key':{'n':format(numbers.n,'x'),'e':numbers.e,
                                          'key_id':hashlib.sha256(spki).hexdigest()[:24]}}
    (PRIVATE/'license-public.json').write_text(json.dumps(public,indent=2)+'\n',encoding='utf-8')
    der=key.private_bytes(serialization.Encoding.DER,serialization.PrivateFormat.PKCS8,serialization.NoEncryption())
    secret_file=PRIVATE/'edge-secrets.env'
    secret_file.write_text('STC_LICENSE_SIGNING_KEY='+base64.b64encode(der).decode()+'\n',encoding='ascii')
    secret_file.chmod(0o600)
    dashboard=ROOT/'supabase/dashboard/stc-license.ts'
    dashboard.parent.mkdir(parents=True,exist_ok=True)
    dashboard.write_text(dashboard_source(),encoding='utf-8')
    print('Prepared the dashboard function, public configuration and private Edge Function secret file.')
    print('Private files: .licensing_private/supabase/ (do not upload to GitHub or share in chat).')
    print('Desktop public key remains unconfigured until the live activation test succeeds.')


def verify():
    config=json.loads((PRIVATE/'license-public.json').read_text(encoding='utf-8'))
    if config['server_url']!=URL:
        raise ValueError('Unexpected licensing project')
    client=LicenseClient(URL,config['public_key'],CredentialStore(PRIVATE/'test-activation.bin'))
    code=getpass.getpass('Enter the temporary test code issued in Supabase SQL Editor (hidden): ').strip().upper()
    first=client.activate(code)
    second=client.check()
    if first['license_id']!=second['license_id']:
        raise ValueError('Activation identity mismatch')
    # A second seat must fail even when it knows the purchased code.
    other=LicenseClient(URL,config['public_key'],CredentialStore(PRIVATE/'unused.bin'),
                        identity=hashlib.sha256((client.device+'different-Windows-seat').encode()).hexdigest())
    try:
        other.activate(code)
    except LicenseError as exc:
        if exc.code!='STC-L102':
            raise
    else:
        raise ValueError('Deployment did not enforce single-seat activation')
    provision_public(config,ROOT)
    print('PASS: live signed activation, saved-token validation and second-seat rejection.')
    print('Desktop public key configured. No EXE was rebuilt and no update was published.')
    print('Revoke the temporary test seat in SQL Editor when finished.')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command',choices=['prepare','verify'])
    args=parser.parse_args()
    try:
        prepare() if args.command=='prepare' else verify()
    except LicenseError as exc:
        print('Deployment verification failed: '+exc.code+'. Check the Supabase setup; no client key was provisioned.')
        return 1
    return 0


if __name__=='__main__':
    sys.exit(main())
