"""Task-based workspace pages; notebook and data survive navigation."""
from pathlib import Path
from PySide6.QtCore import Qt, QUrl
from PySide6.QtGui import QDesktopServices, QIcon, QPixmap
from PySide6.QtWidgets import (
    QApplication, QWidget, QFrame, QLabel, QHBoxLayout, QVBoxLayout, QStackedWidget,
    QCheckBox, QListWidget, QTableView, QSpinBox, QScrollArea, QGridLayout,
)
from .theme import GlassBackground, GlassButton, GlassComboBox
from .charts import ChartViewer
from .stat_options import choose_statistics
from .updates import UpdatesPage

PAGE_KEYS = ("data", "analysis", "charts", "notebook", "exports", "updates", "projects", "geology", "maps", "scene", "relations", "prediction")
LOGO_PATH = Path(__file__).resolve().parent / "assets" / "stc-logo.png"


def card():
    frame = QFrame()
    frame.setObjectName("pageCard")
    layout = QVBoxLayout(frame)
    layout.setContentsMargins(22, 22, 22, 22)
    layout.setSpacing(16)
    return frame, layout


def build_workspace(app):
    app.setWindowTitle("STC Statistics")
    icon = QIcon(str(LOGO_PATH))
    app.setWindowIcon(icon)
    QApplication.instance().setWindowIcon(icon)
    app.resize(1350, 850)
    app.setMinimumSize(1080, 700)
    root = GlassBackground()
    shell = QHBoxLayout(root)
    shell.setContentsMargins(16, 16, 20, 16)
    shell.setSpacing(24)
    nav = QFrame()
    nav.setObjectName("sidebar")
    nav.setFixedWidth(218)
    navigation = QVBoxLayout(nav)
    navigation.setContentsMargins(16, 24, 16, 20)
    navigation.setSpacing(8)
    brand_row = QHBoxLayout()
    brand_row.setSpacing(12)
    app.logo_label = QLabel()
    app.logo_label.setAccessibleName("STC logo")
    app.logo_label.setPixmap(QPixmap(str(LOGO_PATH)).scaled(
        48, 58, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation))
    brand_row.addWidget(app.logo_label)
    wordmark = QLabel("STC")
    wordmark.setObjectName("navBrand")
    brand_row.addWidget(wordmark)
    brand_row.addStretch()
    navigation.addLayout(brand_row)
    product = QLabel("Statistics")
    product.setObjectName("navProduct")
    navigation.addWidget(product)
    company = QLabel("SYSTEM TECHNOLOGIES\nCOMPANY")
    company.setObjectName("eyebrow")
    navigation.addWidget(company)
    navigation.addSpacing(12)
    app.nav_buttons = {}
    nav_scroll = QScrollArea()
    nav_scroll.setWidgetResizable(True)
    nav_scroll.setFrameShape(QFrame.Shape.NoFrame)
    nav_holder = QWidget()
    app.nav_layout = QVBoxLayout(nav_holder)
    app.nav_layout.setContentsMargins(0, 0, 0, 0)
    app.nav_layout.setSpacing(6)
    nav_scroll.setWidget(nav_holder)
    navigation.addWidget(nav_scroll, 1)
    for key in PAGE_KEYS[:6]:
        button = GlassButton()
        button.setObjectName("navigation")
        button.setCheckable(True)
        button.setMinimumHeight(44)
        button.clicked.connect(lambda checked=False, page=key: app.navigate(page))
        app.nav_layout.addWidget(button)
        app.nav_buttons[key] = button
    app.dataset_badge = QLabel()
    app.dataset_badge.setWordWrap(True)
    app.dataset_badge.setObjectName("hint")
    navigation.addWidget(app.dataset_badge)
    app.about_button = app.button("about_stc", lambda: QDesktopServices.openUrl(
        QUrl("https://stc-official.netlify.app/")), navigation)
    app.about_button.setToolTip("https://stc-official.netlify.app/")
    navigation.addSpacing(4)
    app.language_picker = GlassComboBox()
    app.language_picker.addItems(["English", "Français"])
    app.language_picker.setCurrentIndex(0 if app.language == "en" else 1)
    app.language_picker.currentIndexChanged.connect(app.change_language)
    navigation.addWidget(app.language_picker)
    app.motion_toggle = QCheckBox()
    app.motion_toggle.setChecked(bool(app.property("reduceMotion")))
    app.motion_toggle.toggled.connect(app.set_reduce_motion)
    navigation.addWidget(app.motion_toggle)
    shell.addWidget(nav)
    workspace = QVBoxLayout()
    workspace.setSpacing(16)
    app.page_number = QLabel()
    app.page_number.setObjectName("eyebrow")
    workspace.addWidget(app.page_number)
    app.page_title = QLabel()
    app.page_title.setObjectName("pageTitle")
    workspace.addWidget(app.page_title)
    app.page_description = QLabel()
    app.page_description.setObjectName("hint")
    app.page_description.setWordWrap(True)
    workspace.addWidget(app.page_description)
    app.pages = QStackedWidget()
    workspace.addWidget(app.pages, 1)
    shell.addLayout(workspace, 1)

    # DATA — importing, import settings, metrics and a large preview.
    data = QWidget()
    data_layout = QVBoxLayout(data)
    data_layout.setContentsMargins(0, 0, 0, 0)
    data_layout.setSpacing(14)
    actions = QHBoxLayout()
    app.open_button = app.button("import", app.open_file, actions, primary=True)
    app.demo_button = app.button("demo", app.demo, actions)
    actions.addStretch()
    app.import_settings_button = app.button("import_settings", lambda: app.import_settings.setVisible(not app.import_settings.isVisible()), actions)
    data_layout.addLayout(actions)
    metrics = QHBoxLayout()
    app.metric_values = []
    for key in ("rows", "fields", "missing"):
        metric, ml = card()
        metric.setObjectName("metric")
        caption = app.label(key)
        caption.setObjectName("section")
        ml.addWidget(caption)
        value = QLabel("—")
        value.setObjectName("metricValue")
        ml.addWidget(value)
        app.metric_values.append(value)
        metrics.addWidget(metric)
    data_layout.addLayout(metrics)
    app.import_settings, config = card()
    options = QHBoxLayout()
    options.addWidget(app.label("sheet"))
    app.sheet = GlassComboBox()
    options.addWidget(app.sheet, 1)
    options.addWidget(app.label("header"))
    app.header_row = QSpinBox()
    app.header_row.setRange(1, 100000)
    options.addWidget(app.header_row)
    app.reload_button=app.button("apply", app.reload_file, options)
    config.addLayout(options)
    csv = QHBoxLayout()
    csv.addWidget(app.label("csv_sep"))
    app.csv_separator = GlassComboBox()
    for label, value in [(";", ";"), (",", ","), ("Tab", "\t"), ("|", "|")]:
        app.csv_separator.addItem(label, value)
    app.csv_separator.setCurrentIndex(1)
    csv.addWidget(app.csv_separator)
    csv.addWidget(app.label("csv_decimal"))
    app.csv_decimal = GlassComboBox()
    app.csv_decimal.addItems([".", ","])
    csv.addWidget(app.csv_decimal)
    csv.addStretch()
    config.addLayout(csv)
    data_layout.addWidget(app.import_settings)
    app.import_settings.hide()
    preview, preview_layout = card()
    app.data_info = QLabel()
    app.data_info.setWordWrap(True)
    preview_layout.addWidget(app.data_info)
    app.table = QTableView()
    app.table.setAlternatingRowColors(True)
    app.table.setShowGrid(False)
    app.table.verticalHeader().setDefaultSectionSize(37)
    app.table.horizontalHeader().setDefaultSectionSize(150)
    preview_layout.addWidget(app.table, 1)
    app.table.hide()
    app.welcome = QFrame()
    app.welcome.setObjectName("welcome")
    welcome = QVBoxLayout(app.welcome)
    welcome.setAlignment(Qt.AlignmentFlag.AlignCenter)
    app.welcome_title = app.label("welcome")
    app.welcome_title.setObjectName("welcomeTitle")
    app.welcome_title.setAlignment(Qt.AlignmentFlag.AlignCenter)
    welcome.addWidget(app.welcome_title)
    hint = app.label("no_data", wrap=True)
    hint.setAlignment(Qt.AlignmentFlag.AlignCenter)
    welcome.addWidget(hint)
    preview_layout.addWidget(app.welcome, 1)
    preview_layout.addWidget(app.label("formula_note", wrap=True))
    data_layout.addWidget(preview, 1)
    app.pages.addWidget(data)

    # The same column selector moves between Analysis and Charts. Selections persist.
    app.column_panel, column_layout = card()
    column_layout.addWidget(app.label("columns"))
    selection = QHBoxLayout()
    app.button("select", lambda: app.select_columns(True), selection)
    app.button("clear", lambda: app.select_columns(False), selection)
    column_layout.addLayout(selection)
    app.column_list = QListWidget()
    column_layout.addWidget(app.column_list, 1)
    app.column_panel.setMinimumWidth(280)
    app.column_panel.setMaximumWidth(360)
    app.column_hosts = {}
    for key in ("analysis", "charts"):
        page = QWidget()
        row = QHBoxLayout(page)
        row.setContentsMargins(0, 0, 0, 0)
        row.setSpacing(16)
        host = QVBoxLayout()
        host.setContentsMargins(0, 0, 0, 0)
        row.addLayout(host, 1)
        app.column_hosts[key] = host
        content_widget = QWidget()
        content = QVBoxLayout(content_widget)
        content.setContentsMargins(0, 0, 0, 0)
        content.setSpacing(16)
        content_scroll = QScrollArea()
        content_scroll.setWidgetResizable(True)
        content_scroll.setWidget(content_widget)
        row.addWidget(content_scroll, 2)
        if key == "analysis":
            calculation, layout = card()
            layout.addWidget(app.label("stats", wrap=True))
            layout.addWidget(app.label("analysis_help", wrap=True))
            app.button('statistics_options', lambda: choose_statistics(app), layout)
            app.stats_button = app.button("stats", lambda: app.generate("stats"), layout, primary=True)
            layout.addWidget(app.label('correlation_method'))
            app.correlation_method = GlassComboBox()
            app.correlation_method.addItem('Pearson', 'pearson')
            app.correlation_method.addItem('Spearman', 'spearman')
            layout.addWidget(app.correlation_method)
            app.correlation_button = app.button("correlation", lambda: app.generate("correlation"), layout)
            layout.addWidget(app.label("note", wrap=True))
            content.addWidget(calculation)
            clean, layout = card()
            layout.addWidget(app.label("cleaning"))
            layout.addWidget(app.label("conversion", wrap=True))
            app.decimal_comma = QCheckBox()
            layout.addWidget(app.decimal_comma)
            app.convert_button = app.button("convert", app.convert, layout)
            content.addWidget(clean)
        else:
            chart, layout = card()
            layout.addWidget(app.label("kind"))
            app.chart_picker = GlassComboBox()
            layout.addWidget(app.chart_picker)
            layout.addWidget(app.label("charts_help", wrap=True))
            app.chart_button = app.button("create_chart", lambda: app.generate(app.chart_picker.currentData()), layout, primary=True)
            content.addWidget(chart)
        content.addStretch()
        if key == 'charts':
            chart_page = QWidget()
            chart_layout = QVBoxLayout(chart_page)
            chart_layout.setContentsMargins(0, 0, 0, 0)
            chart_tabs = QHBoxLayout()
            app.button('chart_settings', lambda: app.chart_stack.setCurrentIndex(0), chart_tabs)
            app.chart_view_page_button = app.button('view_chart', lambda: app.chart_stack.setCurrentIndex(1), chart_tabs)
            app.chart_view_page_button.setEnabled(False)
            chart_tabs.addStretch()
            chart_layout.addLayout(chart_tabs)
            app.chart_stack = QStackedWidget()
            app.chart_stack.addWidget(page)
            app.chart_viewer = ChartViewer(app)
            app.chart_stack.addWidget(app.chart_viewer)
            chart_layout.addWidget(app.chart_stack, 1)
            app.pages.addWidget(chart_page)
        else:
            app.pages.addWidget(page)

    # NOTEBOOK — all available space is devoted to code and output.
    notebook, notebook_layout = card()
    controls = QHBoxLayout()
    app.add_button = app.button("add", lambda: app.add_cell(), controls)
    app.all_button = app.button("all", app.run_all, controls, primary=True)
    app.stop_button = app.button("stop", app.stop, controls)
    app.restart_button = app.button("restart", app.restart, controls)
    controls.addStretch()
    app.open_notebook_button = app.button("open_notebook", app.open_notebook, controls)
    notebook_layout.addLayout(controls)
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    app.cell_holder = QWidget()
    app.cell_layout = QVBoxLayout(app.cell_holder)
    app.cell_layout.setAlignment(Qt.AlignmentFlag.AlignTop)
    scroll.setWidget(app.cell_holder)
    notebook_layout.addWidget(scroll, 1)
    notebook_layout.addWidget(app.label("about", wrap=True))
    app.pages.addWidget(notebook)

    # EXPORTS — each output type has one clear action.
    exports = QWidget()
    exports_layout = QVBoxLayout(exports)
    exports_layout.setContentsMargins(0, 0, 0, 0)
    options, option_layout = card()
    option_layout.addWidget(app.label('report_content'))
    option_grid = QGridLayout()
    for index, (attribute, key, checked) in enumerate([('report_tables', 'include_tables', True), ('report_graphs', 'include_graphs', True),
                                     ('report_text', 'include_text', True), ('report_code', 'include_code', False)]):
        checkbox = QCheckBox()
        checkbox.setChecked(checked)
        app.bound_labels.append((checkbox, key))
        option_grid.addWidget(checkbox, index // 2, index % 2)
        setattr(app, attribute, checkbox)
    option_layout.addLayout(option_grid)
    exports_layout.addWidget(options)
    report_row = QHBoxLayout()
    for title, help_key, button_key, callback, attribute in [
        ("excel_results", "excel_export_help", "export_results", app.export_results, "result_button"),
        ('word_results', 'word_export_help', 'export_word', app.export_word_report, 'word_button'),
        ("notebook", "notebook_export_help", "export", app.save_notebook, "export_button"),
    ]:
        export_card, layout = card()
        heading = app.label(title)
        heading.setObjectName("cardTitle")
        layout.addWidget(heading)
        layout.addWidget(app.label(help_key, wrap=True))
        buttons = QHBoxLayout()
        setattr(app, attribute, app.button(button_key, callback, buttons, primary=True))
        buttons.addStretch()
        layout.addLayout(buttons)
        if attribute == 'export_button':
            exports_layout.addLayout(report_row)
            exports_layout.addWidget(export_card)
        else:
            report_row.addWidget(export_card, 1)
    exports_layout.addStretch()
    exports_scroll = QScrollArea()
    exports_scroll.setWidgetResizable(True)
    exports_scroll.setWidget(exports)
    app.pages.addWidget(exports_scroll)
    app.updates_page = UpdatesPage(app)
    updates_scroll = QScrollArea()
    updates_scroll.setWidgetResizable(True)
    updates_scroll.setWidget(app.updates_page)
    app.pages.addWidget(updates_scroll)
    app.current_page = "data"
    app.setCentralWidget(root)
